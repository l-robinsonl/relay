-- Relay sync server, PostgreSQL schema (Relay Cloud).
--
-- Everything lives in a dedicated `relay` schema rather than `public`.
-- A Neon database is routinely shared with other applications — a starter
-- template, Neon Auth, a Drizzle-managed app — and `users`, `sessions` and
-- `objects` are names anything might want. Owning a schema means Relay can
-- never collide with, or be collided with by, whatever else is in there,
-- and the whole deployment can be inspected or removed in one statement.
--
-- Mirrors the SQLite schema so the same protocol code runs over both.
-- Differences are only those Postgres forces or clearly rewards:
--
--   * TEXT keys stay TEXT; ids are UUIDv7 strings generated by the client
--     and must match byte for byte across both backends.
--   * BIGINT for revisions and timestamps.
--   * JSONB for payloads, so the server can index into documents later
--     without a migration.
--   * Row-level security, as defence in depth behind the application's own
--     tenant filtering.

CREATE SCHEMA IF NOT EXISTS relay;

CREATE TABLE IF NOT EXISTS relay.users (
    id                TEXT        PRIMARY KEY,
    email             TEXT        NOT NULL,
    email_normalised  TEXT        NOT NULL UNIQUE,
    password_hash     TEXT        NOT NULL,
    display_name      TEXT        NOT NULL DEFAULT '',
    is_server_admin   BOOLEAN     NOT NULL DEFAULT FALSE,
    email_verified_at BIGINT,
    created_at        BIGINT      NOT NULL
);

CREATE TABLE IF NOT EXISTS relay.sessions (
    token_hash   TEXT   PRIMARY KEY,
    user_id      TEXT   NOT NULL REFERENCES relay.users(id) ON DELETE CASCADE,
    created_at   BIGINT NOT NULL,
    expires_at   BIGINT NOT NULL,
    last_seen_at BIGINT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_sessions_user ON relay.sessions (user_id);
CREATE INDEX IF NOT EXISTS idx_sessions_expiry ON relay.sessions (expires_at);

CREATE TABLE IF NOT EXISTS relay.workspaces (
    id         TEXT   PRIMARY KEY,
    name       TEXT   NOT NULL,
    change_seq BIGINT NOT NULL DEFAULT 0,
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS relay.memberships (
    workspace_id TEXT   NOT NULL REFERENCES relay.workspaces(id) ON DELETE CASCADE,
    user_id      TEXT   NOT NULL REFERENCES relay.users(id) ON DELETE CASCADE,
    role         TEXT   NOT NULL CHECK (role IN ('viewer', 'editor', 'admin')),
    created_at   BIGINT NOT NULL,
    PRIMARY KEY (workspace_id, user_id)
);

CREATE INDEX IF NOT EXISTS idx_memberships_user ON relay.memberships (user_id);

CREATE TABLE IF NOT EXISTS relay.objects (
    workspace_id TEXT   NOT NULL REFERENCES relay.workspaces(id) ON DELETE CASCADE,
    kind         TEXT   NOT NULL CHECK (kind IN ('workspace', 'collection', 'request', 'environment')),
    id           TEXT   NOT NULL,
    rev          BIGINT NOT NULL,
    deleted      BOOLEAN NOT NULL DEFAULT FALSE,
    payload      JSONB,
    updated_at   BIGINT NOT NULL,
    updated_by   TEXT,
    PRIMARY KEY (workspace_id, kind, id)
);

CREATE INDEX IF NOT EXISTS idx_objects_rev ON relay.objects (workspace_id, rev);

CREATE TABLE IF NOT EXISTS relay.applied_mutations (
    mutation_id  TEXT   PRIMARY KEY,
    workspace_id TEXT   NOT NULL REFERENCES relay.workspaces(id) ON DELETE CASCADE,
    kind         TEXT   NOT NULL,
    object_id    TEXT   NOT NULL,
    rev          BIGINT NOT NULL,
    applied_at   BIGINT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_applied_workspace ON relay.applied_mutations (workspace_id, applied_at);

CREATE TABLE IF NOT EXISTS relay.invitations (
    id           TEXT   PRIMARY KEY,
    workspace_id TEXT   NOT NULL REFERENCES relay.workspaces(id) ON DELETE CASCADE,
    email        TEXT   NOT NULL,
    role         TEXT   NOT NULL CHECK (role IN ('viewer', 'editor', 'admin')),
    token_hash   TEXT   NOT NULL UNIQUE,
    invited_by   TEXT   NOT NULL REFERENCES relay.users(id) ON DELETE CASCADE,
    created_at   BIGINT NOT NULL,
    expires_at   BIGINT NOT NULL,
    accepted_at  BIGINT
);

CREATE INDEX IF NOT EXISTS idx_invitations_workspace ON relay.invitations (workspace_id);

-- ---------------------------------------------------------------------------
-- Row-level security.
--
-- This is the SECOND lock, not the only one. Every query the application
-- issues is already filtered by workspace, and authorisation is resolved
-- inside the store trait. RLS exists so that a future query which forgets
-- its WHERE clause returns nothing instead of returning another tenant's
-- data.
--
-- The application connects as a role that is subject to these policies and
-- sets `app.user_id` per transaction. A superuser or the table owner
-- bypasses RLS, so the application must NOT connect as either in
-- production; see docs/HOSTING.md.
-- ---------------------------------------------------------------------------

ALTER TABLE relay.workspaces ENABLE ROW LEVEL SECURITY;
ALTER TABLE relay.memberships ENABLE ROW LEVEL SECURITY;
ALTER TABLE relay.objects ENABLE ROW LEVEL SECURITY;
ALTER TABLE relay.invitations ENABLE ROW LEVEL SECURITY;

-- Reads the per-transaction user, or NULL when none is set.
CREATE OR REPLACE FUNCTION relay.current_actor() RETURNS TEXT
LANGUAGE sql STABLE AS $$
    SELECT NULLIF(current_setting('app.user_id', TRUE), '')
$$;

DROP POLICY IF EXISTS workspaces_member_access ON relay.workspaces;
CREATE POLICY workspaces_member_access ON relay.workspaces
    USING (
        EXISTS (
            SELECT 1 FROM relay.memberships m
            WHERE m.workspace_id = relay.workspaces.id
              AND m.user_id = relay.current_actor()
        )
    );

DROP POLICY IF EXISTS memberships_member_access ON relay.memberships;
CREATE POLICY memberships_member_access ON relay.memberships
    USING (
        EXISTS (
            SELECT 1 FROM relay.memberships mine
            WHERE mine.workspace_id = relay.memberships.workspace_id
              AND mine.user_id = relay.current_actor()
        )
    );

DROP POLICY IF EXISTS objects_member_access ON relay.objects;
CREATE POLICY objects_member_access ON relay.objects
    USING (
        EXISTS (
            SELECT 1 FROM relay.memberships m
            WHERE m.workspace_id = relay.objects.workspace_id
              AND m.user_id = relay.current_actor()
        )
    );

DROP POLICY IF EXISTS invitations_admin_access ON relay.invitations;
CREATE POLICY invitations_admin_access ON relay.invitations
    USING (
        EXISTS (
            SELECT 1 FROM relay.memberships m
            WHERE m.workspace_id = relay.invitations.workspace_id
              AND m.user_id = relay.current_actor()
              AND m.role = 'admin'
        )
    );
